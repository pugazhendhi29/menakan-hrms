<?php

/**
 * Writes the 36 management reporting templates (app/Services/ReportCatalog.php) as SQL:
 *   database/migrations/2026_10_31_report_templates.sql  (existing installs)
 *   the "Report templates" block at the end of database/database.sql  (new installs and tests)
 * Run after changing the catalogue:  php bin/make-report-templates-sql.php
 * Every formula is checked before anything is written.
 */

declare(strict_types=1);

require dirname(__DIR__) . '/vendor/autoload.php';

use App\Services\ReportCatalog;
use App\Services\ReportFormula;

$q = fn (?string $s) => $s === null ? 'NULL' : "'" . str_replace(["\\", "'"], ["\\\\", "''"], $s) . "'";
$lines = [];
$count = 0;
foreach (ReportCatalog::templates() as $role => $periods) {
    if (!isset(ReportCatalog::ROLES[$role]) || array_keys($periods) !== array_keys(ReportCatalog::PERIODS)) {
        fwrite(STDERR, "Role $role must be approved and have daily, weekly and monthly templates.\n");
        exit(1);
    }
    foreach ($periods as $period => $fields) {
        $count++;
        $title = ReportCatalog::ROLES[$role][0] . ' - ' . ReportCatalog::PERIODS[$period] . ' Report';
        $lines[] = sprintf("INSERT INTO report_templates (role_code, period, title, version) VALUES (%s, %s, %s, 1);", $q($role), $q($period), $q($title));
        $rows = [];
        $order = 0;
        $keys = [];
        foreach ([['role', $fields], ['standard', ReportCatalog::STANDARD]] as [$section, $list]) {
            foreach ($list as $def) {
                $f = ReportCatalog::field($def);
                if (isset($keys[$f['key']])) {
                    fwrite(STDERR, "Duplicate field {$f['key']} in $role $period.\n");
                    exit(1);
                }
                $keys[$f['key']] = true;
                if ($f['formula'] !== null) {
                    if ($period === 'daily') {
                        fwrite(STDERR, "Daily fields cannot be calculated ($role {$f['key']}).\n");
                        exit(1);
                    }
                    ReportFormula::evaluate($f['formula'], fn () => 1.0);   // throws on a malformed formula
                    $src = ReportFormula::sources($f['formula']);
                    $daily = array_column(array_map([ReportCatalog::class, 'field'], $periods['daily']), 'type', 'key');
                    $weekly = array_column(array_map([ReportCatalog::class, 'field'], $periods['weekly']), 'type', 'key');
                    foreach ($src['daily'] as $k) {
                        if (!isset($daily[$k]) || $daily[$k] === 'text') {
                            fwrite(STDERR, "$role $period {$f['key']}: daily field $k is not a number field.\n");
                            exit(1);
                        }
                    }
                    foreach ($src['weekly'] as $k) {
                        if ($period !== 'monthly' || !isset($weekly[$k]) || $weekly[$k] === 'text') {
                            fwrite(STDERR, "$role $period {$f['key']}: weekly field $k is not available.\n");
                            exit(1);
                        }
                    }
                }
                $rows[] = sprintf("(@t, %s, %s, %s, %s, %s, %s, %d, %d, %d)", $q($section), $q($f['key']), $q($f['label']), $q($f['type']), $q($f['formula']),
                    $q($f['display']), $f['required'] ? 1 : 0, $f['kpi'] ? 1 : 0, ++$order);
            }
        }
        $lines[] = 'SET @t = LAST_INSERT_ID();';
        $lines[] = "INSERT INTO report_template_fields (template_id, section, field_key, label, field_type, formula, display, is_required, is_kpi, sort_order) VALUES\n " . implode(",\n ", $rows) . ';';
    }
}
if ($count !== 36) {
    fwrite(STDERR, "Expected 36 templates, found $count.\n");
    exit(1);
}
$sql = implode("\n", $lines) . "\n";

$migration = "-- The 36 role-specific reporting templates (12 approved job titles x Daily, Weekly, Monthly).\n"
    . "-- Generated by bin/make-report-templates-sql.php from app/Services/ReportCatalog.php - do not edit by hand.\n"
    . "-- Apply after 2026_10_31_management_reporting.sql.\nSET NAMES utf8mb4;\n\n" . $sql;
file_put_contents(dirname(__DIR__) . '/database/migrations/2026_10_31_report_templates.sql', $migration);

$schemaFile = dirname(__DIR__) . '/database/database.sql';
$schema = (string) file_get_contents($schemaFile);
$begin = '-- ---------------------------------------------------------------- Report templates (generated by bin/make-report-templates-sql.php)';
$end = '-- ---------------------------------------------------------------- End of report templates';
$block = "$begin\n$sql$end\n";
$schema = str_contains($schema, $begin)
    ? preg_replace('/' . preg_quote($begin, '/') . '.*?' . preg_quote($end, '/') . "\n?/s", str_replace('$', '\$', $block), $schema)
    : rtrim($schema) . "\n\n" . $block;
file_put_contents($schemaFile, $schema);

fwrite(STDOUT, "Wrote $count templates.\n");
